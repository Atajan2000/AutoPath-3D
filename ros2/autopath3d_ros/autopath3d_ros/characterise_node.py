"""Characterise the Webots Crazyflie + bridge before choosing Webots-specific limits.

Flies, in the free aisle between rack rows 0 and 1 (y = -7, x in [-7, 7]), straight rest-to-rest
trajectories generated by the unchanged AutoPath generator at several speed limits, and brakes
mid-flight on some of them. Measures (ground truth + bridge state): tracking error, achieved speed,
braking latency (command -> deceleration onset), braking distance and deceleration, hover hold
error. Writes <results_dir>/characterisation/characterisation_<stamp>.json.
These measurements set limits / tracking allowance / stopping assumptions in the config; they
are not tuned per scenario.
"""

from __future__ import annotations

import json
import os
import time

import numpy as np
import rclpy
from nav_msgs.msg import Odometry
from rclpy.executors import SingleThreadedExecutor
from std_msgs.msg import String
from trajectory_msgs.msg import MultiDOFJointTrajectory

from autopath3d.trajectories.generator import TrajectoryLimits
from autopath3d.trajectories.polynomial import PiecewisePolynomial, quintic_hermite

from .common import QOS_EVENTS, QOS_LATCHED, AutoPathNode
from .metrics import tracking_stats
from .rosconv import from_time, traj_to_msg

Y, Z = -7.0, 1.2
X_A, X_B = -6.5, 6.5


def straight(a, b, v_max, a_max, t0):
    """Rest-to-rest straight line: accelerate (quintic blend), cruise, decelerate - C2, |a| <= a_max."""
    a, b = np.asarray(a, float), np.asarray(b, float)
    L = float(np.linalg.norm(b - a))
    u = (b - a) / L
    # quintic rest->v blend: peak accel = 1.875 v / T  -> T = 1.875 v / a_max, distance v T / 2
    T1 = 1.875 * v_max / a_max
    d1 = 0.5 * v_max * T1
    if 2 * d1 > L:
        v_max = (L * a_max / 1.875) ** 0.5
        T1 = 1.875 * v_max / a_max
        d1 = 0.5 * v_max * T1
    Tc = (L - 2 * d1) / v_max
    pieces, durs = [], []
    p0, p1, p2, p3 = a, a + d1 * u, b - d1 * u, b
    z = np.zeros(3)
    pieces.append(quintic_hermite(p0, z, z, p1, v_max * u, z, T1)); durs.append(T1)
    if Tc > 1e-6:
        c = np.zeros((6, 3)); c[0], c[1] = p1, v_max * u
        pieces.append(c); durs.append(Tc)
    pieces.append(quintic_hermite(p2, v_max * u, z, p3, z, z, T1)); durs.append(T1)
    return PiecewisePolynomial.from_pieces(pieces, durs, t0)


class CharacteriseNode(AutoPathNode):
    def __init__(self):
        super().__init__("autopath_characterise")
        self.declare_parameter("results_dir", os.path.expanduser("~/autopath_results"))
        self.out = os.path.join(self.get_parameter("results_dir").value, "characterisation")
        self.pub_scene = self.create_publisher(String, "/autopath/scene/request", QOS_EVENTS)
        self.pub_cmd = self.create_publisher(String, "/autopath/bridge/command", QOS_EVENTS)
        self.pub_traj = self.create_publisher(MultiDOFJointTrajectory, "/autopath/active_trajectory", QOS_LATCHED)
        self.events, self.bridge, self.gt = [], [], []
        self.create_subscription(String, "/autopath/events", lambda m: self.events.append(json.loads(m.data)), QOS_EVENTS)
        self.create_subscription(String, "/autopath/bridge/state", lambda m: self.bridge.append(json.loads(m.data)), 200)
        self.create_subscription(Odometry, "/autopath/ground_truth/odom", self._gt, 200)

    def _gt(self, m):
        self.gt.append((from_time(m.header.stamp), [m.pose.pose.position.x, m.pose.pose.position.y,
                        m.pose.pose.position.z], [m.twist.twist.linear.x, m.twist.twist.linear.y, m.twist.twist.linear.z]))

    def wait(self, ex, cond, timeout, what):
        t0 = time.monotonic()
        while not cond():
            ex.spin_once(timeout_sec=0.05)
            if time.monotonic() - t0 > timeout:
                raise TimeoutError(what)

    def ev(self, name, after):
        return [e for e in self.events if e["name"] == name and e["t"] >= after]

    def tnow(self):
        return self.gt[-1][0] if self.gt else 0.0

    def sleep_sim(self, ex, dt):
        t0 = self.tnow()
        self.wait(ex, lambda: self.tnow() >= t0 + dt, 60 + 4 * dt, "sim sleep")

    def run(self, ex):
        self.wait(ex, lambda: self.gt and self.bridge, 120, "simulation")
        self.wait_matched(ex, [self.pub_scene, self.pub_cmd, self.pub_traj])
        self.sleep_sim(ex, 1.0)     # let the drone settle on the floor after spawning
        self.pub_scene.publish(String(data=json.dumps({"name": "place_drone", "xy": [X_A, Y]})))
        self.wait(ex, lambda: self.ev("DRONE_PLACED", 0) or self.ev("PLACE_REFUSED", 0), 20, "placement")
        if self.ev("PLACE_REFUSED", 0):
            raise RuntimeError(f"placement refused: {self.ev('PLACE_REFUSED', 0)[0]['data']}")
        self.sleep_sim(ex, 0.5)
        p = np.array(self.gt[-1][1])
        if np.linalg.norm(p[:2] - [X_A, Y]) > 0.05:
            raise RuntimeError(f"drone not at the characterisation start: {p.tolist()}")
        t_cmd = self.tnow()
        self.pub_cmd.publish(String(data=json.dumps({"cmd": "takeoff", "height": Z})))
        self.wait(ex, lambda: self.ev("TAKEOFF_COMPLETE", t_cmd), 60, "takeoff")
        out = {"takeoff_s": self.ev("TAKEOFF_COMPLETE", t_cmd)[0]["t"] - t_cmd, "runs": []}
        # hover hold
        t0 = self.tnow(); self.sleep_sim(ex, 4.0)
        hb = [s for s in self.bridge if s["t"] >= t0 + 1.0 and "err" in s]
        out["hover"] = tracking_stats(np.array([s["err"] for s in hb]).reshape(-1, 3))
        x_from, x_to = X_A, X_B
        plan = [(0.4, 0.4, None), (0.6, 0.5, None), (0.8, 0.5, None), (1.0, 0.6, None),
                (0.6, 0.5, 0.5), (0.8, 0.5, 0.5), (1.0, 0.6, 0.5), (1.2, 0.6, 0.5)]
        for v_max, a_max, brake_frac in plan:
            p_now = np.array(self.gt[-1][1])
            a, b = np.array([p_now[0], Y, Z]), np.array([x_to, Y, Z])
            tr = straight(a, b, v_max, a_max, self.tnow() + 0.5)
            t_s = tr.t_start
            self.pub_traj.publish(traj_to_msg(tr))
            run = {"v_max": v_max, "a_max": a_max, "from": a.tolist(), "to": b.tolist(), "duration": tr.duration}
            if brake_frac is None:
                self.wait(ex, lambda: self.tnow() > tr.t_end + 3.0, 4 * tr.duration + 60, "run")
            else:
                # brake in the middle of the cruise phase
                t_b = t_s + brake_frac * tr.duration
                self.wait(ex, lambda: self.tnow() >= t_b, 4 * tr.duration + 60, "cruise")
                gt_b = self.gt[-1]
                self.pub_cmd.publish(String(data=json.dumps({"cmd": "brake", "t": gt_b[0]})))
                self.wait(ex, lambda: self.ev("AT_REST", gt_b[0]), 60, "rest")
                rest = self.ev("AT_REST", gt_b[0])[0]
                bs = self.ev("BRAKE_START", gt_b[0] - 0.1)
                G = [g for g in self.gt if gt_b[0] <= g[0] <= rest["t"]]
                tg = np.array([g[0] for g in G]); pg = np.array([g[1] for g in G]); vg = np.array([g[2] for g in G])
                sp = np.linalg.norm(vg[:, :2], axis=1)
                u = np.array(gt_b[2][:2]) / max(np.linalg.norm(gt_b[2][:2]), 1e-9)
                along = (pg[:, :2] - np.array(gt_b[1][:2])) @ u
                k_stop = int(np.argmax(along))
                v0 = float(np.linalg.norm(gt_b[2][:2]))
                # deceleration onset: first sample with speed < v0 - 0.05
                k_on = int(np.argmax(sp < v0 - 0.05)) if np.any(sp < v0 - 0.05) else len(sp) - 1
                k_low = int(np.argmax(sp < 0.05)) if np.any(sp < 0.05) else len(sp) - 1
                run.update(brake_cmd_t=gt_b[0], brake_start_t=bs[0]["t"] if bs else None, speed_at_cmd=v0,
                           stop_distance_from_cmd=float(along[k_stop]),
                           max_overshoot_lateral=float(np.abs((pg[:, :2] - np.array(gt_b[1][:2])) @ np.array([-u[1], u[0]])).max()),
                           decel_onset_delay_s=float(tg[k_on] - gt_b[0]),
                           time_to_speed_005_s=float(tg[k_low] - gt_b[0]),
                           mean_decel=float(v0 / max(tg[k_low] - tg[k_on], 1e-6)),
                           altitude_dev_max=float(np.abs(pg[:, 2] - gt_b[1][2]).max()),
                           rest_t=rest["t"], rest_point=rest["data"]["p"])
                self.sleep_sim(ex, 1.0)
            br = [s for s in self.bridge if t_s <= s["t"] <= tr.t_end and s.get("mode") == "TRACK" and "err" in s]
            run["tracking"] = tracking_stats(np.array([s["err"] for s in br]).reshape(-1, 3))
            G = [g for g in self.gt if t_s <= g[0] <= tr.t_end + 3.0]
            run["max_speed"] = float(max(np.linalg.norm(g[2]) for g in G))
            out["runs"].append(run)
            self.get_logger().info(f"run {json.dumps(run)[:400]}")
            x_from, x_to = x_to, x_from
            self.sleep_sim(ex, 1.5)
        # vertical and diagonal flights (aisle y = -7 is free up to the 3.0 m rack tops and beyond)
        x0 = float(self.gt[-1][1][0])
        dx = -5.0 if x0 > 0 else 5.0
        vert = [("climb", [0.0, 0.0, 1.8], 0.5, 0.5), ("descend", [0.0, 0.0, -1.8], 0.5, 0.5),
                ("diagonal_up", [dx, 0.0, 1.5], 0.8, 0.5), ("diagonal_down", [-dx, 0.0, -1.5], 0.8, 0.5)]
        for kind, d, v_max, a_max in vert:
            p_now = np.array(self.gt[-1][1])
            a = np.array([p_now[0], Y, p_now[2]])
            b = a + np.array(d)
            tr = straight(a, b, v_max, a_max, self.tnow() + 0.5)
            self.pub_traj.publish(traj_to_msg(tr))
            self.wait(ex, lambda: self.tnow() > tr.t_end + 3.0, 4 * tr.duration + 60, kind)
            br = [s for s in self.bridge if tr.t_start <= s["t"] <= tr.t_end and s.get("mode") == "TRACK" and "err" in s]
            run = {"kind": kind, "v_max": v_max, "a_max": a_max, "from": a.tolist(), "to": b.tolist(),
                   "duration": tr.duration,
                   "tracking": tracking_stats(np.array([s["err"] for s in br]).reshape(-1, 3)),
                   "max_speed": float(max(np.linalg.norm(g[2]) for g in self.gt if tr.t_start <= g[0] <= tr.t_end + 3.0)),
                   "final_error": float(np.linalg.norm(np.array(self.gt[-1][1]) - b))}
            out["runs"].append(run)
            self.get_logger().info(f"run {json.dumps(run)[:400]}")
            self.sleep_sim(ex, 1.5)
        out["config"] = {"bridge": self.cfg["bridge"], "limits": self.cfg["limits"]}
        os.makedirs(self.out, exist_ok=True)
        path = os.path.join(self.out, f"characterisation_{time.strftime('%Y%m%d_%H%M%S')}.json")
        json.dump(out, open(path, "w"), indent=1)
        self.get_logger().info(f"CHARACTERISATION written to {path}")


def main():
    rclpy.init()
    node = CharacteriseNode()
    ex = SingleThreadedExecutor()
    ex.add_node(node)
    code = 0
    try:
        node.run(ex)
    except Exception as exc:
        node.get_logger().error(f"characterisation failed: {exc!r}")
        code = 1
    finally:
        node.destroy_node()
        rclpy.try_shutdown()
    raise SystemExit(code)
